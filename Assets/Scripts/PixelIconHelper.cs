    private static readonly Color IconColor = new Color(1f, 0.86f, 0.59f, 1f); // 暖金 #FFDC96
    private const int Size = 24;

    private static Texture2D CreateIcon(string[] rows)
    {
        var tex = new Texture2D(Size, Size, TextureFormat.RGBA32, false);
        tex.filterMode = FilterMode.Point;
        tex.wrapMode = TextureWrapMode.Clamp;
        var colors = new Color[Size * Size];
        // 注意：SetPixels 的 row 0 = 纹理底部，而 rows[0] 是图标顶部 → 必须反转 y
        for (int y = 0; y < Size; y++)
        {
            string row = (y < rows.Length) ? rows[y] : "";
            for (int x = 0; x < Size; x++)
            {
                int idx = (Size - 1 - y) * Size + x;
                if (x < row.Length && row[x] == '#')
                    colors[idx] = IconColor;
                else
                    colors[idx] = Color.clear;
            }
        }
        tex.SetPixels(colors);
        tex.Apply();
        return tex;
    }

