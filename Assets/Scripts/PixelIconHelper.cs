    /// <summary>像素选中态背景纹理（2x2 棋盘格 + 暖金底色）。</summary>
    public static Texture2D ActivePattern()
    {
        var tex = new Texture2D(4, 4, TextureFormat.RGBA32, false);
        tex.filterMode = FilterMode.Point;
        tex.wrapMode = TextureWrapMode.Repeat;
        Color bg = new Color(0.45f, 0.28f, 0.12f, 0.95f);
        Color dot = new Color(0.55f, 0.35f, 0.15f, 0.3f);
        tex.SetPixels(new Color[] {
            bg,  dot, bg,  dot,
            dot, bg,  dot, bg,
            bg,  dot, bg,  dot,
            dot, bg,  dot, bg,
        });
        tex.Apply();
        return tex;
    }
