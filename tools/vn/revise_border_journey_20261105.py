def refresh_log():
 changes=[]
 for p in sorted(SCRIPTS.glob('prologue_*.json')):
  a=json.loads((OUT/'before'/p.name).read_text(encoding='utf-8-sig'));b=json.loads(p.read_text(encoding='utf-8-sig'))
  for si,(x,y) in enumerate(zip(a['scenes'],b['scenes'])):
   for di,(old,new) in enumerate(zip(x['d'],y['d'])):
    if old!=new:changes.append(dict(script=p.stem,scene=si,entry=di,before=old,after=new))
 (OUT/'changes.json').write_text(json.dumps(changes,ensure_ascii=False,indent=2),encoding='utf-8')
 print('BORDER_JOURNEY_UPDATED_ENTRIES',len(changes))

