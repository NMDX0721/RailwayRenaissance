def apply_updates():
 for p in sorted(SCRIPTS.glob('prologue_*.json')):
  raw=p.read_text(encoding='utf-8');j=json.loads(raw)
  fields=[]
  def walk(value,path=()):
   if isinstance(value,dict):
    for k,v in value.items():
     if k=='text':fields.append((path+(k,),v))
     else:walk(v,path+(k,))
   elif isinstance(value,list):
    for i,v in enumerate(value):walk(v,path+(i,))
  walk(j)
  tokens=list(re.finditer(r'"text"\s*:\s*("(?:[^"\\]|\\.)*")',raw))
  assert len(tokens)==len(fields),p.name
  desired={('scenes',si,'d',di,'text'):new for (si,di),new in UPDATES.get(p.stem[9:11],{}).items()}
  edits=[]
  for match,(path,old) in zip(tokens,fields):
   assert json.loads(match.group(1))==old
   if path in desired:edits.append((match.start(1),match.end(1),json.dumps(desired.pop(path),ensure_ascii=False)))
  assert not desired,desired
  for start,end,new in reversed(edits):raw=raw[:start]+new+raw[end:]
  raw=raw.replace('砂能','沙能')
  p.write_text(raw,encoding='utf-8',newline='\n')
 refresh_log()

