# 严格校验
errors = []
total_chars = 0
for s_idx, sc in enumerate(scenes_data):
    thoughts_in_scene = 0
    for d_idx, d in enumerate(sc['d']):
        t = d.get('t', 'd')
        txt = d.get('text', '')
        spk = d.get('s')
        emo = d.get('e')
        total_chars += len(txt)

        if t == 'thought':
            thoughts_in_scene += 1
            if not spk:
                errors.append(f"Scene {s_idx} #{d_idx} thought 缺少 s")
            if not emo:
                errors.append(f"Scene {s_idx} #{d_idx} thought 缺少 e")
            if not (txt.startswith('[') and txt.endswith(']')):
                errors.append(f"Scene {s_idx} #{d_idx} thought 未保留字面方括号: {txt}")
        elif t == 'n':
            if len(txt) > 25:
                errors.append(f"Scene {s_idx} #{d_idx} 旁白超长 ({len(txt)}字 > 25): {txt}")
            if '林彪悍' in txt:
                errors.append(f"Scene {s_idx} #{d_idx} 旁白直呼主角名: {txt}")
        elif t == 'd':
            if spk not in VALID_SPEAKERS:
                errors.append(f"Scene {s_idx} #{d_idx} 非法说话人: {spk}")
        if emo and emo not in VALID_EXPRESSIONS:
            errors.append(f"Scene {s_idx} #{d_idx} 非法表情: {emo}")
    if thoughts_in_scene > 3:
        errors.append(f"Scene {s_idx} thought 数量超标 ({thoughts_in_scene} > 3)")

print("=== 校验结果 ===")
if errors:
    print(f"发现 {len(errors)} 个错误:")
    for e in errors:
        print("  [ERROR]", e)
else:
    print(f"校验全部通过！总字符数: {total_chars}")

